#!/usr/bin/env node
/**
 * Finalize package configuration for dual workspace + publishing workflow.
 *
 * Reverts main/module to src/ for workspace dev (fast pnpm resolution),
 * while keeping exports pointing to dist/ for npm/Verdaccio consumers.
 *
 * This allows:
 * - Workspace: imports from 'package' resolve to src/index.ts (no build needed)
 * - NPM: imports from 'package' resolve to dist/index.js (built, optimized)
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.join(__dirname, '..')
const packagesDir = path.join(rootDir, 'packages')

const CONFIG_ONLY = new Set(['dash-eslint', 'dash-prettier', 'dash-tsconfig'])
const ROOT_ENTRY = new Set(['dash-icons'])
const SKIP = new Set(['react-18-beautiful-dnd-grid'])

function detectEntry(pkgDir, pkgName) {
  if (ROOT_ENTRY.has(pkgName)) return 'index.ts'
  if (fs.existsSync(path.join(pkgDir, 'src', 'index.ts'))) return 'src/index.ts'
  if (fs.existsSync(path.join(pkgDir, 'src', 'index.tsx'))) return 'src/index.tsx'
  return null
}

const pkgNames = fs.readdirSync(packagesDir).filter(name =>
  fs.statSync(path.join(packagesDir, name)).isDirectory()
)

let finalized = 0

for (const pkgName of pkgNames) {
  if (CONFIG_ONLY.has(pkgName) || SKIP.has(pkgName)) continue

  const pkgDir = path.join(packagesDir, pkgName)
  const pkgJsonPath = path.join(pkgDir, 'package.json')
  if (!fs.existsSync(pkgJsonPath)) continue

  const pkg = JSON.parse(fs.readFileSync(pkgJsonPath, 'utf8'))

  const entry = detectEntry(pkgDir, pkgName)
  if (!entry) continue

  // For workspace dev: main/module point to source for fast resolution
  // The workspace symlink resolves directly to src, no build needed
  pkg.main = entry
  if (!pkg.module) pkg.module = entry

  // types still point to dist (generated by tsup or from src)
  pkg.types = 'dist/index.d.ts'

  // exports field: properly configured for npm consumers
  // (already set by prepare-packages.mjs, just ensure it's correct)
  if (!pkg.exports || !pkg.exports['.']) {
    pkg.exports = {
      '.': {
        'types': './dist/index.d.ts',
        'import': './dist/index.js',
        'require': './dist/index.cjs'
      }
    }
  }

  fs.writeFileSync(pkgJsonPath, JSON.stringify(pkg, null, '\t') + '\n')
  console.log(`✓ ${pkgName} (main: ${entry})`)
  finalized++
}

console.log(`\nFinalized ${finalized} packages`)
console.log('\nConfiguration Summary:')
console.log('✓ Workspace: main/module → src/ for fast pnpm resolution')
console.log('✓ NPM/Verdaccio: exports → dist/ for built packages')
console.log('✓ Types: point to dist/index.d.ts')
